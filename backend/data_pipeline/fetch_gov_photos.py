"""현직(지정 연도 이후 재임) 주지사 초상화 파일명 수집 → frontend/src/content/governor_photos.js

Wikipedia REST summary 의 대표 이미지(originalimage) 파일명을 쓴다. 동명이인 방지를 위해
설명(description)에 governor/politician 이 없으면 '이름 (politician)' → 검색('이름 governor 주') 순으로 재시도.
프런트는 en.wikipedia Special:FilePath 로 로드(portraitUrl), 실패 시 이니셜 대체.

실행: python backend/data_pipeline/fetch_gov_photos.py [since_year=2025]
"""
import json
import sqlite3
import sys
import time
import pathlib
import urllib.parse
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
DB = ROOT / "api" / "db" / "election.sqlite"
OUT = ROOT / "frontend" / "src" / "content" / "governor_photos.js"
UA = {"User-Agent": "us-election-map/1.0 (educational project)"}


def get(url, tries=4):
    for i in range(tries):
        try:
            req = urllib.request.Request(url, headers=UA)
            with urllib.request.urlopen(req, timeout=20) as r:
                return json.load(r)
        except urllib.error.HTTPError as e:
            if e.code != 429 or i == tries - 1:
                raise
            time.sleep(15 * (i + 1))     # 요청 제한 → 점점 길게 대기


def lookup(titles):
    """제목 일괄 조회(최대 50) → {요청제목: (최종제목, 설명, 대표이미지 파일명)}. 리다이렉트 추적."""
    r = get("https://en.wikipedia.org/w/api.php?action=query&format=json&redirects=1"
            "&prop=pageimages|description&piprop=name&titles=" + urllib.parse.quote("|".join(titles)))
    q = r.get("query", {})
    alias = {t: t for t in titles}
    for k in ("normalized", "redirects"):
        for m in q.get(k, []):
            for t, v in list(alias.items()):
                if v == m["from"]:
                    alias[t] = m["to"]
    pages = {p["title"]: p for p in q.get("pages", {}).values()}
    out = {}
    for t, final in alias.items():
        p = pages.get(final, {})
        out[t] = (final, p.get("description", "") or "", p.get("pageimage"))
    return out


def ok(info):
    _, desc, img = info
    return img and any(k in desc.lower() for k in ("governor", "politician", "businessman", "attorney", "american"))


def search_title(q):
    r = get("https://en.wikipedia.org/w/api.php?action=query&list=search&format=json&srlimit=1&srsearch="
            + urllib.parse.quote(q))
    hits = r.get("query", {}).get("search", [])
    return hits[0]["title"] if hits else None


def main():
    since = int(sys.argv[1]) if len(sys.argv) > 1 else 2025
    con = sqlite3.connect(DB)
    rows = con.execute(
        """SELECT DISTINCT g.state_po, g.governor_name, s.name FROM governor_terms g
           JOIN state_facts s ON s.region_code = g.region_code
           WHERE g.end_year IS NULL OR g.end_year >= ? ORDER BY g.state_po""", (since,)).fetchall()
    out, miss = {}, []
    names = [n for _, n, _ in rows]
    first = {}
    for i in range(0, len(names), 50):            # 1차: 이름 그대로 일괄 조회
        first.update(lookup(names[i:i + 50]))
        time.sleep(1)
    for po, name, state in rows:
        info = first.get(name)
        if not (info and ok(info)):                # 2차: '(politician)' → 검색
            for t in (f"{name} (politician)", None):
                time.sleep(3)
                try:
                    t = t or search_title(f"{name} governor of {state}")
                    if not t:
                        continue
                    info = lookup([t])[t]
                except Exception as e:          # 한 명 실패로 전체 중단하지 않음(이니셜로 대체됨)
                    print(f"  skip {name}: {e}")
                    continue
                if ok(info):
                    break
        if info and ok(info):
            out[f"{po}|{name}"] = info[2]
            print(f"OK   {po} {name:28s} <- {info[0]} : {info[2]}")
        else:
            miss.append(f"{po} {name}")
            print(f"MISS {po} {name}  ({info})")
    OUT.write_text(
        "// AUTO-GENERATED by backend/data_pipeline/fetch_gov_photos.py — 손으로 수정하지 말 것.\n"
        "// 키 '주약칭|주지사명'(governor_terms 표기) → Wikipedia 대표 이미지 파일명(Special:FilePath 로 로드).\n"
        f"export const GOV_PHOTO = {json.dumps(out, ensure_ascii=False, indent=2)};\n",
        encoding="utf-8")
    print(f"\n{len(out)} found, {len(miss)} missing: {miss}")


if __name__ == "__main__":
    main()
